    static boolean[][] micro(char c) {
        boolean[][] b = MICRO.get(Character.toUpperCase(c));
        if (b == null) b = MICRO.get(fold(c));
        return b == null ? MICRO.get('?') : b;
    }

    public static int microWidth(String s, int tracking) {
        if (s.isEmpty()) return 0;
        int w = 0;
        for (int i = 0; i < s.length(); i++) {
            char c = s.charAt(i);
            w += (c == ' ' ? 2 : micro(c)[0].length) + tracking;
        }
        return w - tracking;
    }

    public static int drawMicro(int[] out, int W, int H, String s, int x, int y, int tracking, int color) {
        for (int i = 0; i < s.length(); i++) {
            char c = s.charAt(i);
            if (c == ' ') {
                x += 2 + tracking;
                continue;
            }
            boolean[][] b = micro(c);
            for (int gy = 0; gy < MICRO_HEIGHT; gy++)
                for (int gx = 0; gx < b[gy].length; gx++) {
                    int px = x + gx, py = y + gy;
                    if (b[gy][gx] && px >= 0 && px < W && py >= 0 && py < H) out[py * W + px] = color;
                }
            x += b[0].length + tracking;
        }
        return x;
    }

    /**
     * Upper case, for drawing. Titles in other scripts (Malayalam, Hindi, Japanese...) are spelled
     * out in Latin letters first, so a song called "മഴ" reads MAZHA rather than ??.
     */
    public static String upper(String s) {
        if (s == null) return "";
        for (int i = 0; i < s.length(); i++) {
            char c = s.charAt(i);
            if (c > 0x024F && GLYPHS.get(fold(c)) == null && MICRO.get(fold(c)) == null) {
                s = latin(s);
                break;
            }
        }
        return s.toUpperCase(Locale.ROOT);
    }

    static Object toLatin;

    static String latin(String s) {
        if (android.os.Build.VERSION.SDK_INT < 29) return s;
        try {
            if (toLatin == null) toLatin = android.icu.text.Transliterator.getInstance("Any-Latin; Latin-ASCII");
            return ((android.icu.text.Transliterator) toLatin).transliterate(s);
        } catch (Exception e) {
            return s;
        }
    }

