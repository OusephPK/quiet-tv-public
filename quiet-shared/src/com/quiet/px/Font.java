    static final int SPACE = 3;

    static boolean[][] glyph(char c) {
        boolean[][] b = GLYPHS.get(Character.toUpperCase(c));
        if (b == null) b = GLYPHS.get(fold(c));
        return b == null ? GLYPHS.get('?') : b;
    }

    /** Accented and odd characters fall back to their plain cousins. */
    static char fold(char c) {
        String s = java.text.Normalizer.normalize(String.valueOf(c), java.text.Normalizer.Form.NFD);
        char base = s.isEmpty() ? '?' : Character.toUpperCase(s.charAt(0));
        if (c == '…') return '.';
        if (c == '—' || c == '–') return '-';
        if (c == '‘' || c == '’' || c == 'ʼ' || c == '`') return '\'';   // curly apostrophes
        if (c == '“' || c == '”') return '"';
        return base;
    }

    public static int width(String s, int scale, int tracking) {
        if (s.isEmpty()) return 0;
        int w = 0;
        for (int i = 0; i < s.length(); i++) {
            char c = s.charAt(i);
            w += (c == ' ' ? SPACE : glyph(c)[0].length) * scale + tracking * scale;
        }
        return w - tracking * scale;
    }

    public static int width(String s, int scale) {
        return width(s, scale, 1);
    }

    /** Draws into a 320×180 ARGB buffer; returns the x after the last glyph. */
    public static int draw(int[] out, int W, int H, String s, int x, int y, int scale, int tracking, int color) {
        for (int i = 0; i < s.length(); i++) {
            char c = s.charAt(i);
            if (c == ' ') {
                x += (SPACE + tracking) * scale;
                continue;
            }
            boolean[][] b = glyph(c);
            for (int gy = 0; gy < HEIGHT; gy++)
                for (int gx = 0; gx < b[gy].length; gx++) {
                    if (!b[gy][gx]) continue;
                    for (int sy = 0; sy < scale; sy++) {
                        int py = y + gy * scale + sy;
                        if (py < 0 || py >= H) continue;
                        for (int sx = 0; sx < scale; sx++) {
                            int px = x + gx * scale + sx;
                            if (px >= 0 && px < W) out[py * W + px] = color;
                        }
                    }
                }
            x += (b[0].length + tracking) * scale;
        }
        return x;
    }

    /** Glyph table as JSON, so a web page can draw the same letters. */
    public static String json() {
        StringBuilder sb = new StringBuilder("{");
        for (Map.Entry<Character, boolean[][]> e : GLYPHS.entrySet()) {
            char c = e.getKey();
            if (c > 0x7e) continue;
            sb.append('"').append(c == '"' || c == '\\' ? "\\" + c : String.valueOf(c)).append("\":[");
            boolean[][] b = e.getValue();
            for (int y = 0; y < HEIGHT; y++) {
                sb.append('"');
                for (boolean v : b[y]) sb.append(v ? '#' : '.');
                sb.append(y < HEIGHT - 1 ? "\"," : "\"");
            }
            sb.append("],");
        }
        sb.setLength(sb.length() - 1);
        return sb.append('}').toString();
    }

